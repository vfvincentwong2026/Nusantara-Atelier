/** 首次访问语言探测：zh* → 中文，en* → English，其余（含 id*）→ 印尼语（市场优先） */
export function detectLocale(navLang: string): Locale {
  const lang = navLang.toLowerCase();
  if (lang.startsWith('zh')) return 'zh';
  if (lang.startsWith('en')) return 'en';
  return 'id';
}
